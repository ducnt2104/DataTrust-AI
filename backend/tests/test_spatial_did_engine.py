"""
Unit tests for Semiparametric Spatial Difference-in-Differences Engine (Spatial-DiD)
(Delgado & Florax 2015; Butts 2021)
DataTrust Iteration 182
"""

import pytest
import numpy as np
from app.engine.spatial_did_engine import run_spatial_diff_in_diff


def test_spatial_did_estimation_success():
    np.random.seed(42)
    n = 45
    records = []

    # Coordinates on a 2D map
    lats = np.random.uniform(10.0, 21.0, size=n)
    lons = np.random.uniform(105.0, 109.0, size=n)
    # Treatment with clustering
    d = (lats > 15.5).astype(float)

    # Simple spatial weights
    diff_lat = lats[:, None] - lats[None, :]
    diff_lon = lons[:, None] - lons[None, :]
    dist = np.sqrt(diff_lat**2 + diff_lon**2)
    dist[dist == 0] = 1e-4
    W = 1.0 / dist
    np.fill_diagonal(W, 0.0)
    W = W / np.sum(W, axis=1, keepdims=True)

    w_d = W @ d

    for i in range(n):
        x1 = float(np.random.normal(50.0, 10.0))
        # Outcome generated by direct effect = 6.0 and spillover = 4.0
        y = 20.0 + 6.0 * d[i] + 4.0 * w_d[i] + 0.3 * x1 + float(np.random.normal(0, 1.0))

        records.append({
            "treatment": d[i],
            "outcome": y,
            "latitude": lats[i],
            "longitude": lons[i],
            "cov1": x1
        })

    res = run_spatial_diff_in_diff(
        records=records,
        treatment_col="treatment",
        outcome_col="outcome",
        lat_col="latitude",
        lon_col="longitude",
        covariate_cols=["cov1"],
        weight_type="inverse_distance",
        power=1.0
    )

    assert res["status"] == "success"
    assert res["sample_size"] == 45
    assert res["direct_effect"]["estimate"] > 3.0
    assert res["spillover_effect"]["estimate"] > 1.0
    assert res["total_impact"]["estimate"] > res["direct_effect"]["estimate"]
    assert "morans_i_diagnostic" in res
    assert "<svg" in res["svg_visualization"]
    assert "DataTrust" in res["apa_narrative"]
    assert "Delgado" in res["apa_narrative"]


def test_spatial_did_insufficient_sample():
    records = [{"treatment": 1, "outcome": 10.0, "latitude": 10.0, "longitude": 105.0} for _ in range(15)]
    res = run_spatial_diff_in_diff(
        records=records,
        treatment_col="treatment",
        outcome_col="outcome",
        lat_col="latitude",
        lon_col="longitude"
    )
    assert res["status"] == "insufficient_data"


def test_spatial_did_invalid_treatment():
    records = [{"treatment": 1, "outcome": float(i), "latitude": 10.0 + i*0.1, "longitude": 105.0} for i in range(30)]
    res = run_spatial_diff_in_diff(
        records=records,
        treatment_col="treatment",
        outcome_col="outcome",
        lat_col="latitude",
        lon_col="longitude"
    )
    assert res["status"] == "invalid_treatment"
